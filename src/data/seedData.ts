export async function seedStoreForUser(
  uid: string,
  displayName: string | null
): Promise<void> {
  const batch = writeBatch(db);
  const storePath = `stores/${uid}`;
  const storeRef = doc(db, 'stores', uid);

  batch.set(storeRef, {
    ownerId: uid,
    storeName: displayName ? `${displayName.split(' ')[0]} Daily Needs & Kirana` : 'Gopal General Store & Daily Needs',
    ownerName: (displayName || 'Store Owner').slice(0, 100),
    location: 'Sudhowala Chowk, Dehradun',
    planStatus: 'trial',
    trialDay: 1,
    consecutiveLogDays: 0,
    weeklyRestockCycles: 0,
    createdAt: serverTimestamp(),
    updatedAt: serverTimestamp(),
  });

  for (const dist of DEMO_DISTRIBUTORS) {
    const distRef = doc(db, 'stores', uid, 'distributors', dist.id);
    batch.set(distRef, {
      ownerId: uid,
      storeId: uid,
      name: dist.name,
      whatsappNumber: dist.whatsappNumber,
      area: dist.area,
      categories: dist.categories,
      avgLeadTimeDays: dist.avgLeadTimeDays,
      createdAt: serverTimestamp(),
      updatedAt: serverTimestamp(),
    });
  }

  for (const item of DEMO_ITEMS) {
    const itemRef = doc(db, 'stores', uid, 'items', item.id);
    batch.set(itemRef, {
      ownerId: uid,
      storeId: uid,
      name: item.name,
      category: item.category,
      unit: item.unit,
      currentStock: item.currentStock,
      dailyVelocity: item.dailyVelocity,
      leadTimeDays: item.leadTimeDays,
      safetyBufferDays: item.safetyBufferDays,
      costPrice: item.costPrice,
      sellingPrice: item.sellingPrice,
      distributorId: item.distributorId,
      distributorName: item.distributorName,
      totalSoldTrial: 0,
      lastLoggedAt: serverTimestamp(),
      createdAt: serverTimestamp(),
      updatedAt: serverTimestamp(),
    });
  }

  try {
    await batch.commit();
  } catch (error) {
    handleFirestoreError(error, OperationType.WRITE, storePath);
  }
}

